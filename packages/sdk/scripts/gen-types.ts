// Writes src/types.ts: the SDK's request and response types, expanded from
// the API's own Zod schemas in @scc/shared by the TypeScript compiler. The SDK
// then ships plain types with no runtime dependency, and they cannot drift:
// `node scripts/gen-types.ts --check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import process from "node:process";

import * as prettier from "prettier";
import type * as TS from "typescript";

// TypeScript is CommonJS; load it the way the API loads wavefile.
const ts = createRequire(import.meta.url)("typescript") as typeof TS;

const sdkDir = path.resolve(import.meta.dirname, "..");
const target = path.join(sdkDir, "src/types.ts");
const entry = path.join(sdkDir, "scripts/__types-entry.ts");

/** Exported name: [z.output or z.input, schema in @scc/shared]. */
const TYPES: Record<string, ["output" | "input", string]> = {
  Me: ["output", "meSchema"],
  Reference: ["output", "referenceSchema"],
  CallList: ["output", "callListSchema"],
  CallListQuery: ["input", "callListQuerySchema"],
  CallDetail: ["output", "callDetailSchema"],
  AudioUrl: ["output", "audioUrlSchema"],
  UploadSignResponse: ["output", "uploadSignResponseSchema"],
  UploadConfirmResponse: ["output", "uploadConfirmResponseSchema"],
  BatchList: ["output", "batchListSchema"],
  BatchListQuery: ["input", "batchListQuerySchema"],
  BatchDetail: ["output", "batchDetailSchema"],
  BatchUpdateRequest: ["input", "batchUpdateRequestSchema"],
  BatchRetryResponse: ["output", "batchRetryResponseSchema"],
  Dashboard: ["output", "dashboardSchema"],
  DashboardQuery: ["input", "dashboardQuerySchema"],
  Highlights: ["output", "highlightsSchema"],
  HighlightsQuery: ["input", "highlightsQuerySchema"],
  Leaderboard: ["output", "leaderboardSchema"],
  LeaderboardQuery: ["input", "leaderboardQuerySchema"],
  WebhookEndpoint: ["output", "webhookEndpointSchema"],
  WebhookEndpointList: ["output", "webhookEndpointListSchema"],
  CreateWebhookRequest: ["input", "createWebhookRequestSchema"],
  UpdateWebhookRequest: ["input", "updateWebhookRequestSchema"],
  CreatedWebhook: ["output", "createdWebhookSchema"],
  WebhookDeliveryList: ["output", "webhookDeliveryListSchema"],
  WebhookDeliveryQuery: ["input", "webhookDeliveryQuerySchema"],
};
/** Plain aliases exported by @scc/shared. */
const ALIASES = ["Language", "BatchExportPart", "WebhookEvent"];

// A coerced query field accepts unknown input; to a caller it is a number.
const source = [
  'import type { z } from "zod";',
  'import type * as s from "@scc/shared";',
  "type Coerced<T> = { [K in keyof T]: unknown extends T[K] ? number | undefined : T[K] };",
  ...Object.entries(TYPES).map(([name, [kind, schema]]) =>
    kind === "input"
      ? `export type ${name} = Coerced<z.input<typeof s.${schema}>>;`
      : `export type ${name} = z.output<typeof s.${schema}>;`,
  ),
  ...ALIASES.map((name) => `export type ${name} = s.${name};`),
].join("\n");

const options: TS.CompilerOptions = {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  exactOptionalPropertyTypes: true,
  allowImportingTsExtensions: true,
  noEmit: true,
  skipLibCheck: true,
};
const host = ts.createCompilerHost(options);
const readSource = host.getSourceFile.bind(host);
host.getSourceFile = (file, language, ...rest) =>
  path.resolve(file) === entry
    ? ts.createSourceFile(file, source, language, true)
    : readSource(file, language, ...rest);
const fileExists = host.fileExists.bind(host);
host.fileExists = (file) => path.resolve(file) === entry || fileExists(file);

const program = ts.createProgram([entry], options, host);
const errors = ts.getPreEmitDiagnostics(program).filter((d) => d.file?.fileName === entry);
if (errors.length > 0) {
  throw new Error(ts.formatDiagnostics(errors, host));
}
const checker = program.getTypeChecker();
const file = program.getSourceFile(entry);
if (!file) throw new Error("the type entry did not load");

const flags =
  ts.TypeFormatFlags.NoTruncation |
  ts.TypeFormatFlags.InTypeAlias |
  ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType;
const lines = [
  "// Generated by scripts/gen-types.ts from the API's schemas in @scc/shared.",
  "// Do not edit: run `pnpm --filter @latte/sdk gen:types` after a schema change.",
  "",
];
for (const statement of file.statements) {
  const exported = ts
    .getModifiers(statement as TS.HasModifiers)
    ?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
  if (!ts.isTypeAliasDeclaration(statement) || !exported) continue;
  const type = checker.getTypeAtLocation(statement.name);
  const text = checker.typeToString(type, undefined, flags);
  // An object type reads as an interface (the lint rule's preference); unions stay types.
  const isObject = !type.isUnionOrIntersection() && (type.flags & ts.TypeFlags.Object) !== 0;
  lines.push(
    isObject
      ? `export interface ${statement.name.text} ${text}`
      : `export type ${statement.name.text} = ${text};`,
  );
}
const generated = `${lines.join("\n")}\n`;

// The output must stand alone: no name it uses may come from another module.
const alone = ts.createSourceFile("types.ts", generated, ts.ScriptTarget.ES2022, true);
const loneHost = ts.createCompilerHost({ noEmit: true, strict: true });
const loneRead = loneHost.getSourceFile.bind(loneHost);
loneHost.getSourceFile = (f, l, ...rest) => (f === "types.ts" ? alone : loneRead(f, l, ...rest));
const lone = ts.createProgram(
  ["types.ts"],
  { noEmit: true, strict: true, lib: ["lib.es2022.d.ts"] },
  loneHost,
);
const loneErrors = ts.getPreEmitDiagnostics(lone);
if (loneErrors.length > 0) {
  throw new Error(
    `generated types do not stand alone:\n${ts.formatDiagnostics(loneErrors, loneHost)}`,
  );
}

const formatted = await prettier.format(generated, {
  ...(await prettier.resolveConfig(target)),
  filepath: target,
});
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== formatted) {
    process.stderr.write("src/types.ts is out of date: run pnpm --filter @latte/sdk gen:types\n");
    process.exit(1);
  }
  process.stdout.write("gen-types: src/types.ts is current\n");
} else {
  writeFileSync(target, formatted);
  process.stdout.write(`gen-types: wrote ${String(lines.length - 3)} types to src/types.ts\n`);
}
